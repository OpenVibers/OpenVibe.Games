const rarityOf = (id: string) => heroes.find((h) => h.id === id)?.rarity ?? 'common'

function makeStages(): StageDef[] {
  const out: StageDef[] = []
  chapterPlan.forEach((plan, c) => {
    for (let k = 1; k <= 10; k++) {
      const s = c * 10 + k
      // A boss stage is the boss and two of the chapter's minions.
      const count = k === 10 ? 3 : s <= 2 ? 2 : s <= 5 ? 3 : s <= 20 ? 4 : 5
      const list: string[] = []
      if (k === 10) list.push(plan.boss)
      while (list.length < count)
        list.push(plan.minions[(s + list.length) % plan.minions.length] as string)
      const shardHero = plan.shardHeroes[k % plan.shardHeroes.length] as string
      const legendary = rarityOf(shardHero) === 'legendary'
      const first: Reward = {
        gold: 250 + 100 * s,
        gems: k === 10 ? 60 : 15,
        shards: [{ hero: shardHero, n: legendary ? 2 : 5 }],
      }
      if (k % 3 === 0) first.sigils = 1
      if (k === 10) {
        first.sigils = 5
        first.gear = [plan.gear]
      }
      out.push({
        index: s,
        chapter: c + 1,
        name: `${chapters[c]?.name ?? ''} ${k}`,
        // The first stages stay at level 1 so the opening minutes are wins.
        level: Math.max(1, Math.round((s - 1) * 1.12 - 1)),
        enemies: list,
        energy: 6,
        first,
        repeat: { gold: 80 + 30 * s, shards: [{ hero: shardHero, n: 1 }] },
      })
    }
  })
  // The first hook: the third stage hands over enough shards to fuse Hana straight away.
  const third = out[2]
  if (third) third.first.shards = [{ hero: 'hana', n: 20 }]
  return out
}

